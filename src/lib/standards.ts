/**
 * The standards label for a catalog entry under the chosen framework.
 * TEKS returns the entry's native label. CCSS returns the crosswalk codes,
 * an explicit "no direct equivalent" note for TEKS-only content, or the
 * native label for entries that live in their own framework (SAT, AP).
 */
export function standardsFor(
  entryId: string,
  nativeLabel: string,
  framework: StandardsFramework
): string {
  if (framework === "teks") return nativeLabel;
  const codes = CCSS_CROSSWALK[entryId];
  if (codes) return `CCSS ${codes}`;
  if (NO_CC_HOME[entryId]) return "CCSS: no direct equivalent";
  return nativeLabel;
}
