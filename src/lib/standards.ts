// Standards frameworks: Texas TEKS (native to the catalog), Common Core
// (CCSS), and further state frameworks as their crosswalks are verified.
// The generators are standards-agnostic; this file is the crosswalk layer.
// Each crosswalk maps a catalog entry id to that framework's code list
// (codes only; display adds the framework's short prefix). A framework's
// NO_HOME record names entries with no direct equivalent there (for CCSS,
// mostly the personal financial literacy strand, which Common Core does
// not have). SAT and AP entries are in no crosswalk: they belong to their
// own frameworks and always display their native label.
//
// Adding a framework = add one meta row to FRAMEWORKS plus one crosswalk
// record (and optionally a NO_HOME record) below. No UI changes needed.

