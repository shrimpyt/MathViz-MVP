/**
 * The standards label for a catalog entry under the chosen framework.
 * TEKS returns the entry's native label. Other frameworks return their
 * crosswalk codes, an explicit "no direct equivalent" note for content
 * the framework does not have, or the native label for entries that live
 * in their own framework (SAT, AP).
 */
export function standardsFor(
  entryId: string,
  nativeLabel: string,
  framework: StandardsFramework
): string {
  if (framework === "teks") return nativeLabel;
  const meta = frameworkMeta(framework);
  const codes = CROSSWALKS[framework]?.[entryId];
  if (codes) return `${meta.short} ${codes}`;
  if (NO_HOME[framework]?.[entryId]) return `${meta.short}: no direct equivalent`;
  return nativeLabel;
}
